"""Stage 3: extract structured, grounded data points from web pages and PDFs.

An extraction schema is a small Pydantic class written as text, usually generated by
`generate_extraction_schema` and reviewed by the user::

    class CholeraCases(BaseModel):
        country: str = Field(..., description="Country the case count is reported for")
        date: str = Field(..., description="Date of the report, in YYYY-MM-DD format")
        cholera_cases: int = Field(..., description="Number of reported cholera cases")

The schema text is **parsed, never executed** (see `parse_extraction_schema`). DataScout adds a
``grounding_quote`` field to the schema; a data point counts as grounded when that quote appears
verbatim in the page, and grounded data points get a text-fragment link to the quote as their source.
"""

from __future__ import annotations

import ast
import json
import re
import urllib.parse
from collections.abc import AsyncGenerator, Sequence
from typing import Any, Optional

from crawl4ai import AsyncWebCrawler, BrowserConfig, CacheMode, CrawlerRunConfig
from crawl4ai import LLMConfig as Crawl4aiLLMConfig
from crawl4ai.extraction_strategy import LLMExtractionStrategy
from mistralai import Mistral
from pydantic import BaseModel, Field, create_model

from .configs import LLMConfig, MistralOCRConfig
from .prompts import GENERATE_EXTRACTION_SCHEMA_PROMPT
from .utils import completion_text, strip_code_fences

__all__ = [
    "GROUNDING_FIELD",
    "SchemaError",
    "extract_data",
    "extract_data_streaming",
    "generate_extraction_schema",
    "is_grounded",
    "parse_extraction_schema",
]

GROUNDING_FIELD = "grounding_quote"
_GROUNDING_DESCRIPTION = (
    "Short span of text taken verbatim from the webpage from which the data is extracted (just a few words), "
    "EXACTLY as it appears in the text, DO NOT miss any words in the middle. "
    "DO NOT include \\ before apostrophes or other special characters."
)
_SCALAR_TYPES: dict[str, type] = {"str": str, "int": int, "float": float, "bool": bool}
_PDF_URL = re.compile(r"\.pdf($|[?#&])", re.IGNORECASE)


class SchemaError(ValueError):
    """Raised when an extraction schema is not a simple Pydantic class that DataScout accepts."""


def generate_extraction_schema(dataset_description: str, schema_fields: list[str], llm_config: LLMConfig) -> str:
    """Ask the LLM to write an extraction schema for ``schema_fields``, plus a field for the data itself.

    Args:
        dataset_description: Plain-language description of the data to collect.
        schema_fields: Fields each data point must have besides the value itself, e.g. ``["country", "date"]``.
        llm_config: LLM settings.

    Returns:
        The schema as Python source text. Review or edit it, then pass it to `extract_data`.
    """
    prompt = GENERATE_EXTRACTION_SCHEMA_PROMPT.format(
        dataset_description=dataset_description, schema_fields=schema_fields
    )
    return strip_code_fences(completion_text(prompt, llm_config))


def _annotation_type(node: ast.expr) -> Any:
    if isinstance(node, ast.Name) and node.id in _SCALAR_TYPES:
        return _SCALAR_TYPES[node.id]
    if isinstance(node, ast.Subscript) and isinstance(node.value, ast.Name):
        inner = _annotation_type(node.slice)
        if node.value.id in ("Optional",):
            return Optional[inner]  # noqa: UP045 - built at runtime from the parsed name
        if node.value.id in ("List", "list"):
            return list[inner]  # type: ignore[valid-type]
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.BitOr):
        if isinstance(node.right, ast.Constant) and node.right.value is None:
            return Optional[_annotation_type(node.left)]  # noqa: UP045
    raise SchemaError(
        f"Unsupported field type {ast.unparse(node)!r}; "
        "use str, int, float or bool, optionally inside Optional[...] or List[...]"
    )


def _field_info(node: ast.expr | None, name: str) -> Any:
    if node is None:
        return Field(...)
    if not (isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and node.func.id == "Field"):
        raise SchemaError(f"Field {name!r} must be assigned Field(...), got {ast.unparse(node)!r}")
    try:
        args = [ast.literal_eval(a) for a in node.args]
        kwargs = {kw.arg: ast.literal_eval(kw.value) for kw in node.keywords if kw.arg}
    except ValueError as exc:
        raise SchemaError(f"Field {name!r}: Field() arguments must be literals") from exc
    unknown = set(kwargs) - {"description", "default", "title", "examples"}
    if unknown or len(args) > 1 or len(node.keywords) != len(kwargs):
        raise SchemaError(f"Field {name!r}: only a default and description=, title=, examples= are allowed")
    default = args[0] if args else kwargs.pop("default", ...)
    return Field(default, **kwargs)


def parse_extraction_schema(schema: str) -> type[BaseModel]:
    """Turn schema text into a Pydantic model, without executing the text.

    The text must define exactly one class that inherits from ``BaseModel``. Its body may contain only
    a docstring and annotated fields of type ``str``, ``int``, ``float`` or ``bool`` (optionally
    inside ``Optional[...]``, ``List[...]`` or ``X | None``), each assigned ``Field(...)`` with literal
    arguments. Markdown code fences around the class are ignored.

    Args:
        schema: The schema source text.

    Returns:
        A Pydantic model class with the same name and fields.

    Raises:
        SchemaError: If the text is not valid Python or uses anything outside that subset.
    """
    try:
        tree = ast.parse(strip_code_fences(schema))
    except SyntaxError as exc:
        raise SchemaError(f"Schema is not valid Python: {exc}") from exc

    classes = [node for node in tree.body if isinstance(node, ast.ClassDef)]
    others = [node for node in tree.body if not isinstance(node, (ast.ClassDef, ast.Import, ast.ImportFrom))]
    if len(classes) != 1 or others:
        raise SchemaError("Schema must contain exactly one class definition and nothing else")
    cls = classes[0]
    if [ast.unparse(b) for b in cls.bases] != ["BaseModel"] or cls.keywords or cls.decorator_list:
        raise SchemaError(f"Class {cls.name!r} must inherit from BaseModel only")

    fields: dict[str, Any] = {}
    for stmt in cls.body:
        if isinstance(stmt, ast.Expr) and isinstance(stmt.value, ast.Constant) and isinstance(stmt.value.value, str):
            continue  # docstring
        if not (isinstance(stmt, ast.AnnAssign) and isinstance(stmt.target, ast.Name)):
            raise SchemaError(f"Unsupported statement in schema: {ast.unparse(stmt)!r}")
        name = stmt.target.id
        if name.startswith("_") or name == GROUNDING_FIELD:
            raise SchemaError(f"Field name {name!r} is reserved")
        fields[name] = (_annotation_type(stmt.annotation), _field_info(stmt.value, name))
    if not fields:
        raise SchemaError(f"Class {cls.name!r} has no fields")

    model: type[BaseModel] = create_model(cls.name, **fields)
    return model


def _with_grounding(model: type[BaseModel]) -> type[BaseModel]:
    grounded: type[BaseModel] = create_model(
        model.__name__, __base__=model, grounding_quote=(str, Field(..., description=_GROUNDING_DESCRIPTION))
    )
    return grounded


def _is_pdf_url(url: str) -> bool:
    return bool(_PDF_URL.search(url))


def _extract_pdf_text(url: str, mistral_ocr_config: MistralOCRConfig) -> str:
    """Return the text of the PDF at ``url``, read with Mistral OCR, as Markdown."""
    client = Mistral(api_key=mistral_ocr_config.api_key)
    ocr_response = client.ocr.process(
        model=mistral_ocr_config.model,
        document={"type": "document_url", "document_url": url},
        include_image_base64=False,
    )
    return "\n".join(page.markdown for page in ocr_response.pages)


def _remove_markdown_links(text: str) -> str:
    """Remove links and images from Markdown, keeping link text."""
    text = re.sub(r"!\[[^\]]*\]\([^)]+\)", "", text)  # images ![alt](url)
    text = re.sub(r"\[\]\([^)]+\)", "", text)  # empty links []()
    text = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", text)  # inline links [text](url)
    text = re.sub(r"\[([^\]]+)\]\[[^\]]+\]", r"\1", text)  # reference links [text][ref]
    text = re.sub(r"^\[[^\]]+\]:\s*.*$", "", text, flags=re.MULTILINE)  # reference definitions
    return text


def _alnum(text: str) -> str:
    return "".join(c for c in text if c.isalnum())


def is_grounded(quote: str | None, page_markdown: str | None) -> bool:
    """Whether ``quote`` appears verbatim in the page, ignoring whitespace, punctuation and Markdown links.

    Both texts are reduced to their alphanumeric characters (after removing Markdown links and images
    from the page) before a case-sensitive substring check, so differences in whitespace, punctuation
    or Markdown formatting don't matter. An empty quote is never grounded.
    """
    quote_chars = _alnum(quote or "")
    if not quote_chars:
        return False
    return quote_chars in _alnum(_remove_markdown_links(page_markdown or ""))


def _datapoints_from_result(url: str, extracted_content: str | None, markdown: str | None) -> list[dict[str, Any]]:
    """Parse crawl4ai's extracted JSON and attach grounding information to each data point."""
    if not extracted_content:
        return []
    try:
        data = json.loads(extracted_content)
    except json.JSONDecodeError:
        return []
    if isinstance(data, dict):
        data = [data]
    if not isinstance(data, list):
        return []

    datapoints = []
    for datapoint in data:
        if not isinstance(datapoint, dict) or datapoint.get("error"):
            continue
        datapoint.pop("error", None)
        grounded = is_grounded(datapoint.get(GROUNDING_FIELD), markdown)
        datapoint["is_grounded"] = grounded
        if grounded:
            datapoint["source"] = f"{url}#:~:text={urllib.parse.quote(str(datapoint[GROUNDING_FIELD]))}"
        else:
            datapoint["source"] = url
        datapoints.append(datapoint)
    return datapoints


def _run_config(model: type[BaseModel], llm_config: LLMConfig, extra_instruction: str | None) -> CrawlerRunConfig:
    instruction = (
        f"From the crawled content, extract all mentioned {model.__name__}. "
        "Only extract a value if it matches what the field describes - no related or similar information. "
    )
    if extra_instruction:
        instruction += extra_instruction
    return CrawlerRunConfig(
        extraction_strategy=LLMExtractionStrategy(
            llm_config=Crawl4aiLLMConfig(provider=llm_config.model, api_token=llm_config.api_key),
            schema=model.model_json_schema(),
            extraction_type="schema",
            instruction=instruction,
            input_format="markdown",
        ),
        cache_mode=CacheMode.BYPASS,
    )


async def extract_data_streaming(
    urls: Sequence[str],
    schema: str,
    llm_config: LLMConfig,
    extra_instruction: str | None = None,
    handle_pdfs: bool = False,
    mistral_ocr_config: MistralOCRConfig | None = None,
    verbose: bool = False,
) -> AsyncGenerator[dict[str, Any], None]:
    """Like `extract_data`, but yield each data point as soon as it is extracted.

    After each URL is processed (whether or not it gave any data), a marker ``{"url_done": url}`` is
    yielded.

    Yields:
        Data points (see `extract_data`) and ``{"url_done": url}`` markers.
    """
    if handle_pdfs and mistral_ocr_config is None:
        raise ValueError("mistral_ocr_config is required when handle_pdfs is True")
    model = _with_grounding(parse_extraction_schema(schema))
    run_config = _run_config(model, llm_config, extra_instruction)

    async with AsyncWebCrawler(config=BrowserConfig(verbose=verbose)) as crawler:
        for url in urls:
            if _is_pdf_url(url):
                if not handle_pdfs:
                    yield {"url_done": url}
                    continue
                assert mistral_ocr_config is not None  # checked above
                target = f"raw:{_extract_pdf_text(url, mistral_ocr_config)}"
            else:
                target = url

            result = await crawler.arun(url=target, config=run_config)
            if result:
                for datapoint in _datapoints_from_result(url, result.extracted_content, result.markdown):
                    yield datapoint
            yield {"url_done": url}


async def extract_data(
    urls: Sequence[str],
    schema: str,
    llm_config: LLMConfig,
    extra_instruction: str | None = None,
    handle_pdfs: bool = False,
    mistral_ocr_config: MistralOCRConfig | None = None,
    verbose: bool = False,
) -> list[dict[str, Any]]:
    """Crawl each URL and have the LLM extract every data point matching ``schema``.

    Pages are fetched and converted to Markdown by [crawl4ai](https://github.com/unclecode/crawl4ai),
    which also runs the LLM extraction. PDF URLs are skipped unless ``handle_pdfs`` is set, in which
    case their text is read with Mistral OCR first.

    Args:
        urls: Pages to extract from.
        schema: Extraction schema text (see `parse_extraction_schema`).
        llm_config: LLM settings (model and API key; the temperature is not used here).
        extra_instruction: Text appended to the extraction instruction.
        handle_pdfs: Whether to process PDF URLs.
        mistral_ocr_config: Required if ``handle_pdfs`` is True.
        verbose: Whether crawl4ai prints its progress log.

    Returns:
        One dict per data point with the schema's fields, plus ``grounding_quote``, ``is_grounded``
        (whether the quote was found in the page) and ``source`` (the URL, with a ``#:~:text=``
        fragment pointing at the quote when it is grounded).

    Raises:
        SchemaError: If ``schema`` is not a valid extraction schema.
        ValueError: If ``handle_pdfs`` is True without ``mistral_ocr_config``.
    """
    return [
        item
        async for item in extract_data_streaming(
            urls, schema, llm_config, extra_instruction, handle_pdfs, mistral_ocr_config, verbose
        )
        if "url_done" not in item
    ]
